// Package engines is the desktop counterpart of Android's EngineBackend: a
// SOCKS connection engine (Psiphon, Tor) runs as a worker process and exposes
// a SOCKS5 listener on 127.0.0.1, and the app routes mihomo through it with
// RuntimeYAML. Engine packages register a Starter here; nothing else in the
// app knows how a particular engine is launched.
//
// Contract for a Starter (mirrors AbstractEngineBackend.start/stop):
//   - ctx bounds startup only. Return only once the engine is connected and its
//     SOCKS port accepts connections, or fail by ctx's deadline (Android: 120 s).
//   - On error, every process and file the attempt created has already been
//     released; a nil Process with an error promises nothing remains.
//   - The returned Process keeps running after ctx ends, until Close.
//   - Done closes when the engine exits for any reason, including Close.
//   - Close stops the engine and returns nil only once its process has exited
//     (resources confirmed released), never merely after asking it to stop.
//   - Never write credentials (bridges, keys, passwords) to Log.
package engines

import (
	"context"
	"fmt"
	"net"
	"sync"
	"time"

	"whitevpn-desktop/internal/engineprofiles"
)

// StartTimeout is how long an engine may take to connect, as on Android.
const StartTimeout = 120 * time.Second

type Process interface {
	SOCKSPort() int
	Done() <-chan struct{}
	Close() error
}

type StartOptions struct {
	Profile engineprofiles.Profile
	// DataDir is this engine kind's own persistent directory under the app
	// config dir; the engine may keep state there across sessions.
	DataDir string
	// Binary returns the path of a shipped executable named as in Engine.Binaries.
	Binary func(name string) (string, error)
	// Log receives sanitized progress lines. May be nil.
	Log func(string)
}

type Starter func(ctx context.Context, opts StartOptions) (Process, error)

type Engine struct {
	Start Starter
	// Binaries are the cores/ file names this engine needs on this platform.
	// Availability requires every one of them to be shipped.
	Binaries []string
}

var (
	mu       sync.RWMutex
	registry = map[engineprofiles.Kind]Engine{}
)

// Register makes an engine kind startable. Only SOCKS kinds can be routed.
func Register(kind engineprofiles.Kind, e Engine) {
	if !kind.SOCKS() || e.Start == nil {
		panic(fmt.Sprintf("engines: invalid registration for %q", kind))
	}
	mu.Lock()
	defer mu.Unlock()
	registry[kind] = e
}

// Unregister exists for tests that register a fake engine.
func Unregister(kind engineprofiles.Kind) {
	mu.Lock()
	defer mu.Unlock()
	delete(registry, kind)
}

func Lookup(kind engineprofiles.Kind) (Engine, bool) {
	mu.RLock()
	defer mu.RUnlock()
	e, ok := registry[kind]
	return e, ok
}

// RuntimeYAML is Android's EngineRuntimeYaml: one socks5 proxy, no UDP (the
// engines carry TCP only), and the two groups the rest of the app selects by
// name. The rules themselves are generated by mihomoconf with RejectUDP.
func RuntimeYAML(port int) (string, error) {
	if port < 1 || port > 65535 {
		return "", fmt.Errorf("engines: invalid SOCKS port")
	}
	return fmt.Sprintf("proxies:\n  - name: %s\n    type: socks5\n    server: 127.0.0.1\n    port: %d\n    udp: false\n", ProxyName, port), nil
}

// ProxyName is the single proxy's name in RuntimeYAML, as on Android.
const ProxyName = "WhiteVPN Engine"

// FreePort asks the system for a free loopback port, as Android's allocatePort.
func FreePort() (int, error) {
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 0, err
	}
	defer l.Close()
	return l.Addr().(*net.TCPAddr).Port, nil
}

// WaitForPort is Android's waitForPort: poll until the SOCKS port accepts a
// connection, failing early when the engine exits.
func WaitForPort(ctx context.Context, port int, done <-chan struct{}) error {
	for {
		select {
		case <-done:
			return fmt.Errorf("engine exited before connecting")
		default:
		}
		c, err := net.DialTimeout("tcp", fmt.Sprintf("127.0.0.1:%d", port), 300*time.Millisecond)
		if err == nil {
			_ = c.Close()
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-done:
			return fmt.Errorf("engine exited before connecting")
		case <-time.After(150 * time.Millisecond):
		}
	}
}
